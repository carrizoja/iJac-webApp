export type Language = 'es' | 'en';
export const translations: Record<Language, TranslationDictionary> = { es, en };

export function isTranslationKey(value: string): value is TranslationKey {
  return Object.prototype.hasOwnProperty.call(es, value);
}

export function translate(
  language: Language,
  key: TranslationKey,
  parameters: Record<string, string | number> = {},
): string {
  return translations[language][key].replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(parameters, name) ? String(parameters[name]) : match,
  );
}
